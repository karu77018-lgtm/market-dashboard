import pandas as pd, numpy as np, io, contextlib, json, sys, warnings; warnings.filterwarnings('ignore')
with contextlib.redirect_stdout(io.StringIO()):
    import epi
n=epi.n; idx=epi.idx
G=pd.read_pickle('episodes_y.pkl'); P=G.iloc[:-1].copy()
KEYS=["days","maxday","bounce","rv20","vix","dvix","sox","spx","small","gv","eqw","dfn","fin","ene","secup","sec50","d10","cred","usd","jpy","tlt","gold","wti","runup","v200","cape","md_yoy","mm_yoy"]
rows=[]
for r in P.to_dict('records'):
    t=idx.get_loc(pd.Timestamp(r['T'])); left=len(n)-1-t
    e={"peak":str(r['peak']),"trigger":str(r['T'])}
    for k in KEYS:
        v=r.get(k); e[k]=None if v is None or (isinstance(v,float) and np.isnan(v)) else round(float(v),2)
    e["inv18"]=None if pd.isna(r['inv18']) else int(r['inv18'])
    e["rec12"]=None if pd.isna(r['rec12']) else int(r['rec12'])
    e["more"]=round(float(r['more']),1) if left>=250 else None
    for h in (20,60,120,250,500):
        e[f"r{h}"]=round(float(n.iloc[t+h]/n.iloc[t]-1)*100,1) if left>=h else None
    rows.append(e)
out='"""Nasdaq-100 corrections since 1990 at the day the -10% line was first crossed (local study,\nresearch/decline-anatomy-2026-11).  Generated by export_ref.py; do not edit by hand.\n\nFactors are measured from the 252-session closing high to that day (index based: ^NDX, ^GSPC,\n^RUT, ^SOX, sector SPDRs from 1999, FRED rates and Baa spread, multpl CAPE, FINRA margin debt,\nFRED retail money funds).  Outcomes: ``more`` = lowest close of the next 250 sessions against\nthat day\'s close (%), ``rN`` = return N sessions later (%), ``rec12`` = NBER recession within\n12 months.  None = not available (series not yet listed, or the outcome has not happened yet).\n"""\nEPISODES = [\n'
for e in rows: out+='    '+json.dumps(e,ensure_ascii=False)+',\n'
out+=']\n'
out=out.replace(': null',': None')
open('/home/claude/md/scripts/decline_reference.py','w').write(out)
print(len(rows),'episodes;','with more:',sum(e['more'] is not None for e in rows))
